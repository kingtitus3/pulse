export default function EmojiPicker({ onSelect, onClose }: EmojiPickerProps) {
  const [selectedCategory, setSelectedCategory] = useState<string>(
    Object.keys(EMOJI_CATEGORIES)[0]
  )

  const categories = Object.keys(EMOJI_CATEGORIES)
  const emojis = EMOJI_CATEGORIES[selectedCategory as keyof typeof EMOJI_CATEGORIES] || []

  return (
    <div className="bg-white border-2 border-gray-400 shadow-lg w-80 h-96 flex flex-col">
      {/* Header */}
      <div className="bg-gray-200 border-b-2 border-gray-400 px-2 py-1 flex justify-between items-center">
        <h3 className="text-xs font-bold">Emoticons</h3>
        <button
          className="text-gray-700 hover:bg-gray-300 px-2 py-0.5 text-sm font-bold"
          onClick={onClose}
        >
          ×
        </button>
      </div>

      {/* Category Tabs */}
      <div className="flex border-b border-gray-400 bg-gray-100 overflow-x-auto">
        {categories.map((cat) => (
          <button
            key={cat}
            onClick={() => setSelectedCategory(cat)}
            className={`px-2 py-1 text-xs whitespace-nowrap border-r border-gray-400 ${
              selectedCategory === cat
                ? 'bg-white border-b-2 border-blue-500 font-bold'
                : 'hover:bg-gray-200'
            }`}
          >
            {cat.split(' ')[0]}
          </button>
        ))}
      </div>

      {/* Emoji Grid */}
      <div className="flex-1 overflow-y-auto p-2">
        <div className="grid grid-cols-8 gap-1">
          {emojis.map((emoji, idx) => (
            <button
              key={`${emoji}-${idx}`}
              onClick={() => onSelect(emoji)}
              className="w-8 h-8 text-lg hover:bg-blue-200 flex items-center justify-center cursor-pointer"
              title={emoji}
            >
              {emoji}
            </button>
          ))}
        </div>
      </div>
    </div>
  )
}

